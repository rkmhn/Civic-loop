/**
 * Universal text localization function
 */
export function tText(text: string, lang: SupportedLanguage): string {
  if (!text || lang === 'en') return text;
  
  const trimmed = text.trim();

  // Check exact phrase dictionary
  if (PHRASE_DICTIONARY[trimmed] && PHRASE_DICTIONARY[trimmed][lang]) {
    return PHRASE_DICTIONARY[trimmed][lang];
  }

  // Check department dictionary
  if (TRANSLATED_DEPARTMENTS[trimmed] && TRANSLATED_DEPARTMENTS[trimmed][lang]) {
    return TRANSLATED_DEPARTMENTS[trimmed][lang];
  }

  // Fallback: If starts with standard patterns like "Near...", "Ticket #...", "Ward #..."
  if (trimmed.startsWith('Near ') || trimmed.startsWith('opposite ') || trimmed.startsWith('Opposite ')) {
    const isOpposite = trimmed.startsWith('opposite ') || trimmed.startsWith('Opposite ');
    const rest = trimmed.substring(isOpposite ? 9 : 5);
    const prefixMap: Record<SupportedLanguage, string> = {
      en: isOpposite ? 'Opposite ' : 'Near ',
      hi: isOpposite ? 'के सामने, ' : 'के पास, ',
      or: isOpposite ? 'ସମ୍ମୁଖ, ' : 'ନିକଟ, ',
      ta: isOpposite ? 'எதிரில், ' : 'அருகில், ',
      te: isOpposite ? 'ఎదురుగా, ' : 'సమీపంలో, ',
      kn: isOpposite ? 'ಎದುರು, ' : 'ಬಳಿ, ',
      mr: isOpposite ? 'समोर, ' : 'जवळ, ',
      bn: isOpposite ? 'বিপরীতে, ' : 'কাছে, '
    };
    return `${rest} ${prefixMap[lang] || ''}`.trim();
  }

  return text;
}
